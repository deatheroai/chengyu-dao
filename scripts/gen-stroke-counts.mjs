// Writes src/story-builder/strokeCounts.ts: every character in
// hanzi-writer-data with 8 strokes or fewer, grouped by stroke count, so
// 教团团写字 can tell an easy character (人, 大) from a challenging one
// without loading stroke data. Characters not listed have 9+ strokes.
//   npm run gen:stroke-counts
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const root = fileURLToPath(new URL("..", import.meta.url));
const dataDir = dirname(require.resolve("hanzi-writer-data/人.json"));
const MAX = 8;

const buckets = Array.from({ length: MAX + 1 }, () => []);
for (const file of readdirSync(dataDir).sort()) {
  const char = file.replace(/\.json$/, "");
  if (!file.endsWith(".json") || Array.from(char).length !== 1) continue;
  const n = JSON.parse(readFileSync(`${dataDir}/${file}`, "utf8")).strokes.length;
  if (n <= MAX) buckets[n].push(char);
}

const rows = buckets.map((chars, n) => `  ${JSON.stringify(chars.join(""))}, // ${n}`).join("\n");
writeFileSync(
  `${root}src/story-builder/strokeCounts.ts`,
  `/**
 * GENERATED by scripts/gen-stroke-counts.mjs — do not edit by hand.
 * Characters with ${MAX} strokes or fewer, by stroke count (index = strokes),
 * from hanzi-writer-data 2.0.1 (derived from Make Me a Hanzi), under the
 * Arphic Public License — see
 * src/idiom-door/writingData/writingStrokeData.LICENSE.txt.
 */
const BY_STROKES: readonly string[] = [
${rows}
];

const COUNTS = new Map<string, number>();
BY_STROKES.forEach((chars, n) => {
  for (const c of chars) COUNTS.set(c, n);
});

/** Stroke count of \`char\`, or ${MAX + 1} for any character with more than ${MAX} strokes. */
export function strokeCount(char: string): number {
  return COUNTS.get(char) ?? ${MAX + 1};
}
`,
);
