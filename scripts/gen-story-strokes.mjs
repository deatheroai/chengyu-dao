// Bundles hanzi-writer-data stroke data for just the target characters
// of every story in src/reading/stories.ts, into
// src/reading/storyStrokeData.ts. Rerun after changing a story:
//   npm run gen:story-strokes
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const root = fileURLToPath(new URL("..", import.meta.url));
const storiesSrc = readFileSync(`${root}src/reading/stories.ts`, "utf8");
const chars = [...new Set([...storiesSrc.matchAll(/char:\s*"(.)"/gu)].map((m) => m[1]))];

const entries = chars.map((c) => {
  const { strokes, medians, radStrokes } = require(`hanzi-writer-data/${c}.json`);
  return `  ${JSON.stringify(c)}: ${JSON.stringify({ strokes, medians, radStrokes })},`;
});

writeFileSync(
  `${root}src/reading/storyStrokeData.ts`,
  `/**
 * GENERATED by scripts/gen-story-strokes.mjs — do not edit by hand.
 * Stroke-order data for the story target characters, from
 * hanzi-writer-data 2.0.1 (derived from Make Me a Hanzi), under the
 * Arphic Public License — see
 * src/idiom-door/writingData/writingStrokeData.LICENSE.txt.
 */
import type { WritingCharacterData } from "../idiom-door/writingData/writingStrokeData";

export const storyStrokeData: Record<string, WritingCharacterData> = {
${entries.join("\n")}
};
`,
);
console.log(`Bundled stroke data for ${chars.length} characters: ${chars.join(" ")}`);
